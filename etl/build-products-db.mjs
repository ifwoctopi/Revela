// Builds the on-device product database from the Open Beauty Facts bulk CSV
// export, and bundles thumbnails for the most-scanned face-care products.
//
// Usage (repo root, Node 22.13+ for node:sqlite):
//   node etl/build-products-db.mjs
//
// Outputs (both consumed by the mobile app):
//   mobile/assets/db/products.db                        (git-ignored, ~12 MB)
//   mobile/assets/product-thumbs/*.jpg + index.ts        (committed, < 1 MB)
//
// The mobile app's background sync (mobile/src/products/sync.ts) keeps text
// records fresh after install; re-run this script to refresh the bundled copy.

import { mkdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { Readable } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { createGunzip } from 'node:zlib';
import { DatabaseSync } from 'node:sqlite';

const EXPORT_URL = 'https://static.openbeautyfacts.org/data/en.openbeautyfacts.org.products.csv.gz';
const IMAGE_HOST = 'https://images.openbeautyfacts.org';
const MOBILE = new URL('../mobile/', import.meta.url);
const DB_PATH = new URL('assets/db/products.db', MOBILE);
const THUMBS_DIR = new URL('assets/product-thumbs/', MOBILE);
const BUNDLED_THUMBS = 40;

// Must match FACE_CARE_SQL_TERMS in mobile/src/products/classify.ts.
const FACE_CARE_CATEGORY = /skin|face|facial|moistur|cleans|serum|sunscreen|sun-protection|toner|acne|eye-cream|exfoli/;

// Only these fields are stored: essential text metadata plus the image path
// (relative to IMAGE_HOST) and the fields needed for filtering and sync.
const SCHEMA = `
CREATE TABLE products (
  barcode       TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  brand         TEXT NOT NULL,
  ingredients   TEXT NOT NULL,
  categories    TEXT NOT NULL,
  image_path    TEXT,
  last_modified INTEGER NOT NULL
);
CREATE INDEX products_last_modified ON products(last_modified);
CREATE TABLE sync_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);
`;

async function* rows() {
  const response = await fetch(EXPORT_URL);
  if (!response.ok) throw new Error(`Export download failed: HTTP ${response.status}`);
  const lines = createInterface({ input: Readable.fromWeb(response.body).pipe(createGunzip()) });
  let header;
  for await (const line of lines) {
    const values = line.split('\t');
    if (!header) {
      header = values;
      continue;
    }
    yield Object.fromEntries(header.map((key, i) => [key, values[i] ?? '']));
  }
}

function toProduct(row) {
  const name = row.product_name.trim();
  const ingredients = row.ingredients_text.trim();
  if (!row.code || !name || ingredients.length < 20) return null;
  return {
    barcode: row.code,
    name,
    brand: row.brands.split(',')[0].trim(),
    ingredients,
    categories: row.categories_tags,
    image_path: row.image_small_url.startsWith(IMAGE_HOST) ? row.image_small_url.slice(IMAGE_HOST.length) : null,
    last_modified: Number(row.last_modified_t) || 0,
    scans: Number(row.unique_scans_n) || 0,
  };
}

async function main() {
  mkdirSync(new URL('.', DB_PATH), { recursive: true });
  if (existsSync(DB_PATH)) rmSync(DB_PATH);
  const db = new DatabaseSync(fileURLToPath(DB_PATH));
  db.exec(SCHEMA);

  const insert = db.prepare(
    'INSERT OR REPLACE INTO products VALUES (:barcode, :name, :brand, :ingredients, :categories, :image_path, :last_modified)',
  );
  const popular = [];
  let count = 0;
  let newest = 0;

  console.log('Downloading and importing the Open Beauty Facts export...');
  db.exec('BEGIN');
  for await (const row of rows()) {
    const product = toProduct(row);
    if (!product) continue;
    const { scans, ...record } = product;
    insert.run(record);
    count++;
    newest = Math.max(newest, record.last_modified);
    if (scans > 0 && record.image_path && FACE_CARE_CATEGORY.test(record.categories)) popular.push(product);
  }
  db.prepare("INSERT INTO sync_state VALUES ('last_modified', ?)").run(String(newest));
  db.exec('COMMIT');
  db.exec('VACUUM');
  db.close();
  console.log(`Imported ${count} products.`);

  // Thumbnails for the most-scanned face-care products ship with the app.
  popular.sort((a, b) => b.scans - a.scans);
  rmSync(THUMBS_DIR, { recursive: true, force: true });
  mkdirSync(THUMBS_DIR, { recursive: true });
  const bundled = [];
  for (const product of popular.slice(0, BUNDLED_THUMBS)) {
    const response = await fetch(IMAGE_HOST + product.image_path);
    if (!response.ok) continue;
    writeFileSync(new URL(`${product.barcode}.jpg`, THUMBS_DIR), Buffer.from(await response.arrayBuffer()));
    bundled.push(product.barcode);
  }
  writeFileSync(
    new URL('index.ts', THUMBS_DIR),
    `// Generated by etl/build-products-db.mjs. Do not edit.\n\n` +
      `export const bundledThumbnails: Record<string, number> = {\n` +
      bundled.map((code) => `  '${code}': require('./${code}.jpg'),\n`).join('') +
      `};\n`,
  );
  console.log(`Bundled ${bundled.length} thumbnails.`);
}

await main();
